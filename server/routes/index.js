import { Router } from 'express';
import { protect, adminOnly } from '../middleware/auth.js';
import { validate, validateId } from '../middleware/validate.js';
import { registerSchema, loginSchema, bookSchema, categorySchema } from '../validators/schemas.js';
import * as auth from '../controllers/authController.js';
import * as books from '../controllers/bookController.js';
import * as cats from '../controllers/categoryController.js';
import { stats } from '../controllers/dashboardController.js';
import * as borrows from '../controllers/borrowController.js';
const r = Router();
r.param('id', validateId);
r.post('/auth/register', validate(registerSchema), auth.register);
r.post('/auth/login', validate(loginSchema), auth.login);
r.get('/auth/me', protect, auth.me);
r.get('/books', protect, books.list);
r.get('/books/:id', protect, books.get);
r.post('/books', protect, adminOnly, validate(bookSchema), books.create);
r.put('/books/:id', protect, adminOnly, validate(bookSchema), books.update);
r.delete('/books/:id', protect, adminOnly, books.remove);
r.get('/categories', protect, cats.list);
r.post('/categories', protect, adminOnly, validate(categorySchema), cats.create);
r.put('/categories/:id', protect, adminOnly, validate(categorySchema), cats.update);
r.delete('/categories/:id', protect, adminOnly, cats.remove);
r.get('/dashboard/stats', protect, stats);
r.get('/borrows/my', protect, borrows.myBorrows);
r.get('/borrows/all', protect, adminOnly, borrows.adminBorrows);
r.post('/borrows', protect, borrows.borrow);
r.put('/borrows/:id/return', protect, borrows.returnBook);
export default r;
